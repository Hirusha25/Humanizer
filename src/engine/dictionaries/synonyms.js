let index = null;
/** word -> list of alternatives, lowercase. Multi-word keys allowed. */
export function synonymIndex() {
  if (index) return index;
  index = new Map();
  for (const group of SYNONYM_GROUPS) {
    for (const w of group) {
      if (NEVER_SWAP.has(w)) continue;
      const alts = group.filter((x) => x !== w && !(w.indexOf(' ') === -1 && x.indexOf(' ') !== -1));
      if (!alts.length) continue;
      const existing = index.get(w) || [];
      for (const a of alts) if (!existing.includes(a)) existing.push(a);
      index.set(w, existing);
    }
  }
  return index;
}

const blockIndex = new Map();
for (const [w, re] of CONTEXT_BLOCKS) {
  if (!blockIndex.has(w)) blockIndex.set(w, []);
  blockIndex.get(w).push(re);
}
export function isBlocked(word, sentence) {
  const list = blockIndex.get(word);
  if (!list) return false;
  return list.some((re) => re.test(sentence));
}
